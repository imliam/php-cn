<?php

declare(strict_types=1);

use Cn\Contracts\ValidatorContract;
use Cn\Support\ClassMap;
use Cn\Support\Config;
use Cn\ValueObjects\ClassPartObject;

require dirname(__DIR__) . '/vendor/autoload.php';

$check = false;
$outputPath = null;

foreach (array_slice($argv, 1) as $argument) {
    if ($argument === '--check') {
        $check = true;
    } elseif ($argument === '--help') {
        fwrite(STDOUT, "Usage: php scripts/compile-default-config.php [--check] [output-path]\n");
        exit(0);
    } elseif (str_starts_with($argument, '-') || $outputPath !== null) {
        fwrite(STDERR, "Usage: php scripts/compile-default-config.php [--check] [output-path]\n");
        exit(1);
    } else {
        $outputPath = $argument;
    }
}

$outputPath ??= dirname(__DIR__) . '/src/Support/CompiledConfigData.php';
$configuration = Config::getDefaultConfig();
$classMap = ClassMap::create($configuration);
$groups = array_map(strval(...), array_keys($configuration['classGroups']));
$groupIds = array_flip($groups);
$classes = [];
$validators = [];

// Keep the trie traversal order. Validators at the deepest matching prefix run
// first at runtime, and validators sharing a prefix retain declaration order.
$visit = static function (ClassPartObject $node, string $prefix) use (&$visit, &$classes, &$validators, $groupIds): void {
    if ($node->classGroupId !== null) {
        $classes[$prefix] = $groupIds[$node->classGroupId];
    }

    foreach ($node->validators as $validator) {
        $reflection = new ReflectionFunction($validator->validator);
        $validatorClass = $reflection->getClosureCalledClass();

        if ($validatorClass === null || ! $validatorClass->implementsInterface(ValidatorContract::class)
            || $reflection->getName() !== 'validate' || ! $reflection->isStatic()
            || $reflection->getClosureThis() !== null || $reflection->getStaticVariables() !== []) {
            throw new RuntimeException("Cannot compile validator for class group '{$validator->classGroupId}': expected a named static ValidatorContract::validate method.");
        }

        $method = $validatorClass->getMethod('validate');

        if (! $method->isPublic() || ! $method->isStatic()) {
            throw new RuntimeException("Cannot compile non-public or non-static validator {$validatorClass->getName()}::validate.");
        }

        $validators[$prefix][] = [$validatorClass->getName(), $groupIds[$validator->classGroupId]];
    }

    foreach ($node->nextPart as $part => $child) {
        $visit($child, $prefix === '' ? (string) $part : $prefix . '-' . $part);
    }
};

$visit($classMap, '');
$maxValidatorPrefixLength = 0;

foreach (array_keys($validators) as $prefix) {
    $maxValidatorPrefixLength = max($maxValidatorPrefixLength, strlen((string) $prefix));
}

$configuration['theme'] = [];
$configuration['classGroups'] = [];
$sourceHash = hash_file('sha256', dirname(__DIR__) . '/src/Support/default-config.php');

if ($sourceHash === false) {
    throw new RuntimeException('Cannot hash the default configuration.');
}

$compiled = [
    'configuration' => $configuration,
    'groups' => $groups,
    'classes' => $classes,
    'validators' => $validators,
    'maxValidatorPrefixLength' => $maxValidatorPrefixLength,
    'sourceHash' => $sourceHash,
];

// Emit PHP literals only: loading the artifact creates no closures, theme
// getters, or trie objects. Keep short scalar lists on one line for review.
$exportScalar = static function (mixed $value): string {
    if (is_string($value) && is_a($value, ValidatorContract::class, true)) {
        return '\\' . $value . '::class';
    }

    return $value === null ? 'null' : var_export($value, true);
};

$export = static function (mixed $value, int $depth = 0) use (&$export, $exportScalar): string {
    if (! is_array($value)) {
        return $exportScalar($value);
    }

    if ($value === []) {
        return '[]';
    }

    if (array_is_list($value) && count(array_filter($value, is_array(...))) === 0) {
        $inline = '[' . implode(', ', array_map($exportScalar, $value)) . ']';

        if (strlen($inline) + ($depth * 4) <= 120) {
            return $inline;
        }
    }

    $indent = str_repeat('    ', $depth + 1);
    $rows = [];
    $list = array_is_list($value);

    foreach ($value as $key => $item) {
        $rows[] = $indent . ($list ? '' : var_export($key, true) . ' => ') . $export($item, $depth + 1) . ',';
    }

    return "[\n" . implode("\n", $rows) . "\n" . str_repeat('    ', $depth) . ']';
};

$source = "<?php\n\ndeclare(strict_types=1);\n\nnamespace Cn\\Support;\n\n"
    . "// Generated by scripts/compile-default-config.php; do not edit by hand.\n"
    . "// Source: src/Support/default-config.php.\n"
    . "// MIT license: resources/upstream/tailwind-merge-LICENSE.md\n"
    . "/**\n * @internal\n *\n * @phpstan-import-type Tables from CompiledClassMap\n */\n"
    . "final class CompiledConfigData\n{\n"
    . "    /**\n     * @return Tables\n     */\n"
    . "    public static function get(): array\n    {\n"
    . '        return ' . $export($compiled, 2) . ";\n    }\n}\n";

if ($check) {
    if (! is_file($outputPath) || file_get_contents($outputPath) !== $source) {
        fwrite(STDERR, "Compiled configuration is stale. Run php scripts/compile-default-config.php.\n");
        exit(1);
    }

    fwrite(STDOUT, "Compiled configuration is up to date.\n");
    exit(0);
}

if (file_put_contents($outputPath, $source) === false) {
    throw new RuntimeException("Cannot write compiled configuration to {$outputPath}.");
}

fwrite(STDOUT, sprintf("Compiled %d groups, %d exact classes, and %d validator prefixes to %s.\n", count($groups), count($classes), count($validators), $outputPath));
