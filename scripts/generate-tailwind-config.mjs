/** Generate the PHP default configuration from a pinned tailwind-merge checkout.
 * Usage: node scripts/generate-tailwind-config.mjs /path/to/tailwind-merge
 * Requires Node.js 22.13+ (built-in TypeScript stripping); no npm dependencies.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { stripTypeScriptTypes } from 'node:module'
import { resolve } from 'node:path'
import { runInNewContext } from 'node:vm'
import { execFileSync } from 'node:child_process'

const revision = 'bceabfd95eab05553d15c5368b2684de697a84eb'
const checkout = process.argv[2]
if (!checkout) throw new Error('Provide a tailwind-merge checkout at ' + revision)
if (execFileSync('git', ['rev-parse', 'HEAD'], { cwd: checkout, encoding: 'utf8' }).trim() !== revision) {
    throw new Error('Checkout must be pinned to ' + revision)
}
const source = readFileSync(resolve(checkout, 'src/lib/default-config.ts'), 'utf8')
const validatorNames = [...source.matchAll(/\b(is\w+),?\s*$/gm)].map(match => match[1])
const validatorClass = name => name === 'isAny' ? 'AnyValueValidator' : name.slice(2) + 'Validator'
const context = { fromTheme: key => ({ themeKey: key }) }
for (const name of validatorNames) context[name] = { validator: validatorClass(name) }
const code = stripTypeScriptTypes(source, { mode: 'strip' })
    .replace(/^import[\s\S]*?from '[^']+'\s*/gm, '')
    .replace('export const getDefaultConfig', 'const getDefaultConfig')
const config = runInNewContext(code + '\ngetDefaultConfig()', context)
config.prefix = null
const quote = value => "'" + value.replaceAll('\\', '\\\\').replaceAll("'", "\\'") + "'"
const render = (value, depth = 0) => {
    if (value === null) return 'null'
    if (typeof value === 'number' || typeof value === 'boolean') return String(value)
    if (typeof value === 'string') return quote(value)
    if (value.validator) return `\\Cn\\Validators\\${value.validator}::validate(...)`
    if (value.themeKey) return `new \\Cn\\ValueObjects\\ThemeGetter(${quote(value.themeKey)})`
    const entries = Array.isArray(value) ? value.map(item => render(item, depth + 1)) : Object.entries(value).map(([key, item]) => `${quote(key)} => ${render(item, depth + 1)}`)
    if (!entries.length) return '[]'
    if (entries.every(item => !item.includes('\n')) && entries.join(', ').length < 140) return '[' + entries.join(', ') + ']'
    const indent = '    '.repeat(depth + 1)
    return '[\n' + entries.map(entry => indent + entry + ',').join('\n') + '\n' + '    '.repeat(depth) + ']'
}
writeFileSync('src/Support/default-config.php', `<?php\n\ndeclare(strict_types=1);\n\n// Generated by scripts/generate-tailwind-config.mjs; do not edit by hand.\n// tailwind-merge 3.6.0 (${revision}), Tailwind CSS 4.0–4.3.\n// MIT license: resources/upstream/tailwind-merge-LICENSE.md\nreturn ${render(config)};\n`)
writeFileSync('resources/upstream/tailwind-merge-LICENSE.md', readFileSync(resolve(checkout, 'LICENSE.md')))
console.log(`Generated ${Object.keys(config.classGroups).length} class groups and ${Object.keys(config.conflictingClassGroups).length} conflict entries.`)
